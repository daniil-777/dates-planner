/**
 * The handle to read from: the one passed in, else the running server's `cds.db`.
 *
 * `global.cds` is set by `@sap/cds` the moment it is loaded, so a CAP process
 * always has it and a bare Node process never does — which is exactly the
 * distinction this needs to make, without importing the module and requiring it
 * to be installed wherever this file is imported.
 */
async function resolveDb(handle: unknown): Promise<StatementDb> {
  if (handle !== undefined && handle !== null) {
    if (isDb(handle)) return handle
    throw new StatementError('the db handle passed to aggregateYear() has no run() method')
  }

  const cds = (globalThis as { cds?: unknown }).cds
  if (isRecord(cds)) {
    if (isDb(cds.db)) return cds.db
    if (isConnect(cds.connect)) {
      const connected: unknown = await cds.connect.to('db')
      if (isDb(connected)) return connected
    }
  }
  throw new StatementError(
    'no CAP database is connected — run aggregateYear() inside a CAP service or pass a db handle',
  )
}

/** Confirmed expenses of the year, oldest first (§8 needs the date order). */
